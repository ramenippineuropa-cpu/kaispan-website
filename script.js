const textNodes = [];
function collectTextNodes() {
  const skip = new Set(["SCRIPT", "STYLE"]);
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (skip.has(node.parentElement?.tagName)) return NodeFilter.FILTER_REJECT;
      return node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  while (walker.nextNode()) {
    const node = walker.currentNode;
    node._sourceText = node.nodeValue;
    textNodes.push(node);
  }
}

function applyLanguage(lang) {
  currentLanguage = lang;
  document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
  const titles = {
    zh: "KaiSpan - 餐饮与零售企业的 AI 运营助手",
    en: "KaiSpan - AI operations assistant for restaurants and retail",
    de: "KaiSpan - KI-Betriebsassistent für Gastronomie und Handel",
    ja: "KaiSpan - 飲食・小売向け AI 運営アシスタント",
    ko: "KaiSpan - 외식 및 리테일을 위한 AI 운영 어시스턴트",
    vi: "KaiSpan - Trợ lý vận hành AI cho nhà hàng và bán lẻ"
  };
  document.title = titles[lang] || titles.zh;
  const phraseDict = derivedLanguage(lang);
  if (lang === "zh") {
    document.querySelectorAll("[data-source-text]").forEach((element) => {
      element.textContent = element.dataset.sourceText;
    });
  }
  textNodes.forEach((node) => {
    const source = node._sourceText;
    const trimmed = source.trim();
    const translated = phraseDict[trimmed];
    const leading = source.match(/^\s*/)[0];
    const trailing = source.match(/\s*$/)[0];
    node.nodeValue = translated ? `${leading}${translated}${trailing}` : source;
  });
  document.querySelectorAll("body *").forEach((element) => {
    if (element.childNodes.length === 1 && element.firstChild?.nodeType === 3) {
      const exact = element.textContent.trim();
      if (phraseDict[exact]) {
        if (!element.dataset.sourceText) element.dataset.sourceText = exact;
        element.textContent = phraseDict[exact];
      }
    }
  });
  applyKeyedTranslations(lang);
  updateHeroDashboard(lang);
}


const siteHeader = document.querySelector(".site-header");
const menuToggle = document.querySelector(".menu-toggle");
const mobileMenu = document.getElementById("mobileMenu");
function closeMobileMenu() {
  siteHeader?.classList.remove("menu-open");
  menuToggle?.setAttribute("aria-expanded", "false");
}
menuToggle?.addEventListener("click", () => {
  const open = siteHeader.classList.toggle("menu-open");
  menuToggle.setAttribute("aria-expanded", String(open));
});
mobileMenu?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", closeMobileMenu);
});
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeMobileMenu();
});

document.querySelectorAll("a[href^='#']").forEach((link) => {
  link.addEventListener("click", (event) => {
    const target = document.querySelector(link.getAttribute("href"));
    if (target) {
      event.preventDefault();
      target.scrollIntoView({ behavior: "smooth", block: "start" });
    }
  });
});

document.querySelectorAll(".problem-card").forEach((card) => {
  card.addEventListener("click", () => {
    document.getElementById(card.dataset.target)?.scrollIntoView({ behavior: "smooth", block: "center" });
  });
});

document.querySelectorAll(".detail-toggle").forEach((button) => {
  button.addEventListener("click", () => {
    const details = button.closest(".role-module").querySelector(".role-details");
    details.hidden = !details.hidden;
    button.textContent = translatePhrase(details.hidden ? "View Details" : "Hide Details");
  });
});

document.querySelectorAll(".demo-tabs button").forEach((tab) => {
  tab.addEventListener("click", () => {
    const panel = tab.closest(".demo-panel");
    panel.querySelectorAll(".demo-tabs button").forEach((item) => item.classList.remove("active"));
    tab.classList.add("active");
    panel.querySelector("h4").textContent = translatePhrase(tab.dataset.title);
    panel.querySelector("p").textContent = translatePhrase(tab.dataset.desc);
    panel.querySelector(".watch-demo").dataset.demo = tab.dataset.title;
  });
});

